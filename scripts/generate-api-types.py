"""Regenerate public TypeScript types from the checked-in versioned JSON Schema."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def convert(spec):
    if "$ref" in spec:
        return spec["$ref"].split("/")[-1]
    if "const" in spec:
        return json.dumps(spec["const"])
    if "enum" in spec:
        return " | ".join(json.dumps(x) for x in spec["enum"])
    if "anyOf" in spec:
        return " | ".join(convert(x) for x in spec["anyOf"])
    t = spec["type"]
    if t == "array":
        return "(" + convert(spec["items"]) + ")[]"
    if t == "object":
        if "properties" not in spec:
            return "{ [key: string]: " + convert(spec["additionalProperties"]) + " }"
        return (
            "{\n"
            + "\n".join(
                "  " + json.dumps(k) + ("" if k in spec.get("required", []) else "?") + ": " + convert(v) + ";"
                for k, v in spec["properties"].items()
            )
            + "\n}"
        )
    return {"integer": "number", "number": "number", "string": "string", "boolean": "boolean", "null": "null"}[t]


def render():
    schema = json.loads((ROOT / "design/api/state-v1.schema.json").read_text())
    return (
        "// Generated by scripts/generate-api-types.py; edit the schema first.\n"
        + "\n\n".join(
            "export type " + name + " = " + convert(s) + ";"
            for name, s in {**schema["$defs"], "GameState": schema}.items()
        )
        + "\n"
    )


if __name__ == "__main__":
    (ROOT / "src/drugstory/career/web/api-types.d.ts").write_text(render())
